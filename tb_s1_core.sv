// tb_s1_core : integration testbench -- RV64I vs spike            [WIP]
// Description  :
// Runs an RV64I program through the assembled core and checks every retirement
// against spike: order, pc, instruction, destination, written value, next pc.
//
// Nothing here models the ISA.  `prog.svh` is generated by gen.py from the
// toolchain -- the image with riscv64-unknown-elf-objcopy, the expectations
// from spike's commit log -- so a bug in this testbench cannot agree with a
// matching bug in the DUT.  Regenerate after editing rv64i.s:
//
//     python3 gen.py
//
// Everything the core declares as external is tied off rather than modelled,
// because nothing in this program reaches it:
//
//   D$ port        no load or store is executed
//   chk_*, pma_*   the PMA and PMP query, only driven by a data access
//   md_*           no RV64M instruction is executed
//   irq_i          no interrupt is raised
//
// Those tie-offs are the point: they prove the signals are wired and the core
// elaborates and runs without the three external blocks existing.  When a
// block arrives, replace its tie-off, not the testbench.
//
// Run:  make test
// =============================================================================

module tb_s1_core
  import s1_pkg::*;
;


  logic clk = 1'b0, rst_n = 1'b0;
  initial forever #5 clk = ~clk;

  // ---------------------------------------------------------------------------
  // Core
  // ---------------------------------------------------------------------------
  logic     imem_req_valid, imem_req_ready, imem_rsp_valid, imem_rsp_ready;
  mem_req_t imem_req;
  mem_rsp_t imem_rsp;
  logic     dmem_req_valid, dmem_req_ready, dmem_rsp_valid, dmem_rsp_ready;
  mem_req_t dmem_req;
  mem_rsp_t dmem_rsp;
  irq_t     irq;
  logic     fence_i, store_err;
  logic [XLEN-1:0] store_err_addr;
  logic [XLEN-1:0] chk_addr;
  logic [2:0]      chk_size;
  logic            chk_rd, chk_wr, chk_ex;
  priv_lvl_e       chk_priv;
  pma_t            pma;
  logic            pma_fault, pmp_allow;
  logic [PMP_N-1:0][7:0]      pmpcfg;
  logic [PMP_N-1:0][PLEN-3:0] pmpaddr;
  logic            md_start, md_flush, md_done;
  muldiv_op_e      md_op;
  logic [XLEN-1:0] md_a, md_b, md_result;
  rvfi_t           rvfi;

  s1_core #(.RESET_PC(PROG_BASE)) dut (
    .clk_i(clk), .rst_ni(rst_n),
    .imem_req_valid_o(imem_req_valid), .imem_req_ready_i(imem_req_ready),
    .imem_req_o(imem_req), .imem_rsp_valid_i(imem_rsp_valid),
    .imem_rsp_ready_o(imem_rsp_ready), .imem_rsp_i(imem_rsp),
    .dmem_req_valid_o(dmem_req_valid), .dmem_req_ready_i(dmem_req_ready),
    .dmem_req_o(dmem_req), .dmem_rsp_valid_i(dmem_rsp_valid),
    .dmem_rsp_ready_o(dmem_rsp_ready), .dmem_rsp_i(dmem_rsp),
    .irq_i(irq), .fence_i_o(fence_i),
    .store_err_o(store_err), .store_err_addr_o(store_err_addr),
    .chk_addr_o(chk_addr), .chk_size_o(chk_size), .chk_rd_o(chk_rd),
    .chk_wr_o(chk_wr), .chk_ex_o(chk_ex), .chk_priv_o(chk_priv),
    .pma_i(pma), .pma_fault_i(pma_fault), .pmp_allow_i(pmp_allow),
    .pmpcfg_o(pmpcfg), .pmpaddr_o(pmpaddr),
    .md_start_o(md_start), .md_op_o(md_op), .md_a_o(md_a), .md_b_o(md_b),
    .md_flush_o(md_flush), .md_done_i(md_done), .md_result_i(md_result),
    .rvfi_o(rvfi)
  );

  // ---------------------------------------------------------------------------
  // Tie-offs for the three external blocks and the data port
  // ---------------------------------------------------------------------------
  always_comb begin
    dmem_req_ready = 1'b1;              // accept, but nothing is ever issued
    dmem_rsp_valid = 1'b0;
    dmem_rsp       = '0;
    irq            = '0;
    // permissive PMA and PMP: never queried, since no data access occurs
    pma            = '0;
    pma.cacheable  = 1'b1;
    pma.idempotent = 1'b1;
    pma.atomic_lrsc= 1'b1;
    pma.atomic_amo = 1'b1;
    pma_fault      = 1'b0;
    pmp_allow      = 1'b1;
    md_done        = 1'b0;              // no RV64M instruction is executed
    md_result      = '0;
  end

  // ---------------------------------------------------------------------------
  // Instruction memory.  One beat is XLEN wide and fetch selects the 32-bit
  // lane with addr[2], so a request returns the doubleword containing it.
  // ---------------------------------------------------------------------------
  logic [31:0] imem [0:255];

  `include "prog.svh"

  localparam logic [XLEN-1:0] BASE    = PROG_BASE;
  localparam logic [XLEN-1:0] LOOP_PC = SPIN_PC;

  function automatic logic [31:0] word_at(logic [XLEN-1:0] a);
    logic [XLEN-1:0] off;
    off = a - BASE;
    if (a < BASE || off[XLEN-1:2] >= N_WORDS) return 32'h0000_0013;   // nop
    return imem[off[9:2]];
  endfunction

  assign imem_req_ready = 1'b1;

  always_ff @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      imem_rsp_valid <= 1'b0;
      imem_rsp       <= '0;
    end else begin
      imem_rsp_valid <= 1'b0;
      imem_rsp       <= '0;
      if (imem_req_valid && imem_req_ready) begin
        logic [XLEN-1:0] beat;
        beat             = {imem_req.addr[XLEN-1:3], 3'b000};
        imem_rsp_valid   <= 1'b1;
        imem_rsp.rdata   <= {word_at(beat + 4), word_at(beat)};
        imem_rsp.err     <= 1'b0;
        imem_rsp.id      <= imem_req.id;
      end
    end
  end

  // ---------------------------------------------------------------------------
  // Expected retirement stream
  // ---------------------------------------------------------------------------
  int unsigned checks = 0, errors = 0, retired = 0, cyc = 0, spun = 0;

  always_ff @(posedge clk) if (rst_n) cyc <= cyc + 1;

  logic [XLEN-1:0] e_pc    [N_EXP];
  logic [ILEN-1:0] e_insn  [N_EXP];
  logic [4:0]      e_rd    [N_EXP];
  logic [XLEN-1:0] e_wdata [N_EXP];
  logic [XLEN-1:0] e_npc   [N_EXP];
  int unsigned     n_exp = N_EXP;

  task automatic exp(int unsigned o, logic [XLEN-1:0] pc, logic [ILEN-1:0] insn,
                     logic [4:0] rd, logic [XLEN-1:0] wd, logic [XLEN-1:0] npc);
    e_pc[o] = pc; e_insn[o] = insn; e_rd[o] = rd; e_wdata[o] = wd; e_npc[o] = npc;
  endtask

  task automatic check(input string name, input logic [XLEN-1:0] got,
                       input logic [XLEN-1:0] want);
    checks++;
    if (got !== want) begin
      errors++;
      if (errors <= 20)
        $display("  FAIL retire %0d  %-10s got=0x%016h want=0x%016h",
                 retired, name, got, want);
    end
  endtask

  // ---------------------------------------------------------------------------
  // Check every retirement
  // ---------------------------------------------------------------------------
  always_ff @(posedge clk) begin
    if (rst_n && rvfi.valid) begin
      if (retired >= n_exp) begin
        // Past the program: the last instruction is `beq x0, x0, 0`, so every
        // further retirement must be that same spin, at the same pc, writing
        // nothing.  Anything else means the core ran off the end.
        check("spin pc",       rvfi.pc_rdata, LOOP_PC);
        check("spin pc_wdata", rvfi.pc_wdata, LOOP_PC);
        check("spin writes nothing", XLEN'(rvfi.rd_addr), 0);
        spun++;
      end else begin
        check("order",    rvfi.order,     XLEN'(retired));
        check("pc",       rvfi.pc_rdata,  e_pc[retired]);
        check("insn",     XLEN'(rvfi.insn), XLEN'(e_insn[retired]));
        check("rd_addr",  XLEN'(rvfi.rd_addr), XLEN'(e_rd[retired]));
        check("rd_wdata", rvfi.rd_wdata,  e_wdata[retired]);
        check("pc_wdata", rvfi.pc_wdata,  e_npc[retired]);
        check("no trap",  XLEN'(rvfi.trap), 0);
      end
      retired++;
    end
  end

  // ---------------------------------------------------------------------------
  // Program and run
  // ---------------------------------------------------------------------------
  initial begin
    for (int i = 0; i < 256; i++) imem[i] = 32'h0000_0013;   // nop
    load_program();
    load_expected();

    repeat (4) @(posedge clk);
    #1 rst_n = 1'b1;

    // A cycle counter rather than a forked watchdog: 5.020 rejects `repeat`
    // inside fork with %Error-LIFETIME.
    wait (retired >= n_exp || cyc > 20000);
    repeat (8) @(posedge clk);          // let the spin retire a few times
    if (retired < n_exp) begin
      $display("  FAIL watchdog: only %0d of %0d retired after %0d cycles",
               retired, n_exp, cyc);
      errors++;
    end

    check("every instruction retired", XLEN'(retired >= n_exp), 1);
    check("no store error",            XLEN'(store_err), 0);
    check("no spurious data access",   XLEN'(dmem_req_valid), 0);
    check("no multiply dispatched",    XLEN'(md_start), 0);

    check("the spin was reached", XLEN'(spun > 0), 1);
    $display("retired %0d of %0d program instructions, then spun %0d times",
             n_exp, n_exp, spun);
    if (errors != 0) $fatal(1, "=== FAIL : %0d of %0d checks ===", errors, checks);
    $display("=== PASS : %0d checks ===", checks);
    $finish;
  end
endmodule
