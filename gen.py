#!/usr/bin/env python3
"""Build the testbench program image and its expected retirement stream from
the RISC-V toolchain: the image comes from objcopy, the expectations from spike.
Nothing here models the ISA."""
import re, subprocess, sys, pathlib

BASE = 0x80000000
SRC  = "rv64i.s"
ELF  = "rv64i.elf"
RV   = "/opt/riscv/bin"

# ---- assemble and link at BASE ---------------------------------------------
subprocess.run([f"{RV}/riscv64-unknown-elf-gcc", "-march=rv64i", "-mabi=lp64",
                "-nostdlib", "-nostartfiles", "-Wl,-N", "-Wl,--build-id=none",
                f"-Ttext=0x{BASE:x}", "-e", "_start", "-o", ELF, SRC],
               check=True, capture_output=True, text=True)

# ---- image: objcopy -> flat binary -> 32-bit words ---------------------------
subprocess.run([f"{RV}/riscv64-unknown-elf-objcopy", "-O", "binary",
                "--only-section=.text", ELF, "prog.bin"], check=True)
blob  = pathlib.Path("prog.bin").read_bytes()
words = [int.from_bytes(blob[i:i+4], "little") for i in range(0, len(blob), 4)]

# ---- expectations: spike commit log ----------------------------------------
spin = BASE + len(blob) - 4                      # the final self-branch
cmds = pathlib.Path("cmds"); cmds.write_text(f"until pc 0 {hex(spin)}\nq\n")
log = subprocess.run([f"{RV}/spike", "--isa=rv64i", "--log-commits",
                      "-d", "--debug-cmd=cmds", ELF],
                     capture_output=True, text=True).stderr

# core   0: 3 0x<pc> (0x<insn>) x<rd>  0x<val>
LINE = re.compile(r"^core\s+\d+:\s+\d+\s+0x([0-9a-f]+)\s+\(0x([0-9a-f]+)\)(?:\s+x\s*(\d+)\s+0x([0-9a-f]+))?")
recs = []
for ln in log.splitlines():
    m = LINE.match(ln.strip())
    if not m: continue
    pc = int(m.group(1), 16)
    if pc < BASE or pc > spin: continue          # skip spike's bootrom
    recs.append(dict(pc=pc, insn=int(m.group(2), 16),
                     rd=int(m.group(3)) if m.group(3) else 0,
                     val=int(m.group(4), 16) if m.group(4) else 0))

# pc_wdata is the next retirement's pc.  Spike's `until pc 0 <spin>` halts WHEN
# pc becomes the spin, before executing it, so the log never contains the spin
# and the final real instruction has no successor in the log -- its successor is
# the spin by construction.
recs = [r for r in recs if r["pc"] != spin]
for i in range(len(recs) - 1):
    recs[i]["npc"] = recs[i+1]["pc"]
if recs:
    recs[-1]["npc"] = spin
if not recs:
    sys.exit("no retirements parsed from spike -- check the log format")

out = ["// GENERATED by gen.py -- do not edit.",
       "// Image from riscv64-unknown-elf-objcopy; expectations from spike.",
       f"// {len(words)} words, {len(recs)} retirements, base 0x{BASE:x}", ""]
out.append(f"localparam int unsigned N_WORDS = {len(words)};")
out.append(f"localparam int unsigned N_EXP   = {len(recs)};")
out.append(f"localparam logic [63:0] PROG_BASE = 64'h{BASE:x};")
out.append(f"localparam logic [63:0] SPIN_PC   = 64'h{spin:x};")
out.append("")
out.append("task automatic load_program();")
for i, w in enumerate(words):
    out.append(f"  imem[{i}] = 32'h{w:08x};")
out.append("endtask")
out.append("")
out.append("task automatic load_expected();")
for i, r in enumerate(recs):
    out.append(f"  exp({i}, 64'h{r['pc']:x}, 32'h{r['insn']:08x}, 5'd{r['rd']}, "
               f"64'h{r['val']:016x}, 64'h{r['npc']:x});")
out.append("endtask")
pathlib.Path("prog.svh").write_text("\n".join(out) + "\n")
print(f"prog.svh: {len(words)} words, {len(recs)} retirements")
